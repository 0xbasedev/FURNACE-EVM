// pnpm provisional — the register of every provisional reading [P] taken across the ADRs
// (docs/PROVISIONAL.md). Each [P] is a spec gap read as recommended under the owner's standing
// rule; each is a deploy blocker until the owner confirms it. The register is generated from the
// ADRs themselves, so it can never drift: `pnpm provisional:check` (part of `pnpm check`) fails
// when it is stale. To confirm a reading, edit its ADR (drop the [P] and record the decision),
// then regenerate.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const DIR = 'docs/adr';
const OUT = 'docs/PROVISIONAL.md';
// Lines that only announce a list of readings, not a reading.
const HEADER = /Provisional readings \[P\]|provisional where marked \[P\]|\[P\], taken as|each \[P\]|every \[P\]|\(\[P\]\)\s*$/i;

const adrs = readdirSync(DIR).filter((f) => /^\d{4}-.*\.md$/.test(f)).sort();
const sections = [];
let total = 0;
for (const f of adrs) {
  const text = readFileSync(`${DIR}/${f}`, 'utf8');
  const title = (text.match(/^# (.*)$/m) ?? [, f])[1];
  const items = [];
  for (const raw of text.split('\n')) {
    if (!raw.includes('[P]') || HEADER.test(raw)) continue;
    const line = raw
      .replace(/^\s*(?:[-*]|\d+\.)\s+/, '')
      .replace(/\*\*\[P\]\*\*\s*/g, '')
      .replace(/\*\*\[P\]\s*/g, '**')
      .replace(/\[P\]\s*/g, '')
      .replace(/\*\*\*\*/g, '')
      .replace(/ \*\*(?=[.,;:)\s]|$)/g, '**')
      .replace(/ +\)/g, ')')
      .replace(/\s{2,}/g, ' ')
      .trim();
    if (line) items.push(line);
  }
  if (items.length === 0) continue;
  total += items.length;
  const id = f.slice(0, 4);
  sections.push(`## [ADR ${id}](adr/${f}): ${title.replace(/^ADR \d{4}:\s*/, '')}\n\n${items.map((t, i) => `${i + 1}. \`P-${id}-${i + 1}\` ${t}`).join('\n')}`);
}

const body = `# Provisional readings register

**Generated by \`pnpm provisional\` from the ADRs. Do not edit by hand.**

Each entry is a gap or ambiguity in the sealed spec (\`canonical/\`, v5.5.0, pinned by \`SHA256SUMS.json\` and the config hash; see [SPEC-SEAL.md](SPEC-SEAL.md)). Each was read as recommended, under the owner's standing rule ("Always choose your recommendations"), and marked [P] in its ADR. **Every entry is a deploy blocker until the owner confirms it.** To confirm or change one, edit its ADR (drop the [P] and record the decision), then run \`pnpm provisional\`. \`pnpm check\` fails while this file is stale.

**${total} provisional readings across ${sections.length} ADRs.**

${sections.join('\n\n')}
`;

if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
  if (cur !== body) {
    console.error(`✗ ${OUT} is stale — run pnpm provisional`);
    process.exit(1);
  }
  console.log(`✓ ${OUT}: ${total} provisional readings, current`);
} else {
  writeFileSync(OUT, body);
  console.log(`wrote ${OUT}: ${total} provisional readings across ${sections.length} ADRs`);
}
